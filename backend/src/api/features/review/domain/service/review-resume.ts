import { REVIEW_JOB_STATUS } from "../model/review";

/**
 * 途中で終わった審査を、そのジョブのまま続きから流せるか。
 *
 * 以前は続きも「再審査」として別のジョブを作っていた。済んだ項目を
 * 写すので結果は正しいが、中止したジョブが一覧に残り続ける。利用者から
 * 見れば同じ書類を同じチェックリストで見ているだけなのに、履歴が2行に
 * 増える。どちらが本物か分からなくなる。
 *
 * 続きは条件が何も変わらない。同じ文書、同じチェックリスト、同じ部署。
 * 変わるのは「まだ判定していない項目を埋める」ことだけなので、ジョブを
 * 増やす理由がない。
 *
 * 文書を差し替えてもう一度見てもらうのは別の話で、そちらは元の結果を
 * 残したまま新しいジョブを作る（再審査）。完了した審査をここに含めない
 * のはそのため。完了しているなら埋める項目がない。
 *
 * まだ走っているものも含めない。同じ項目を二重に審査してしまう
 */
export const canResume = (status: REVIEW_JOB_STATUS): boolean =>
  status === REVIEW_JOB_STATUS.FAILED || status === REVIEW_JOB_STATUS.CANCELLED;
